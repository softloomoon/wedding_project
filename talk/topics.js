/* 랜덤 질문 카드 (메인 3번 칸). 같은 질문이 연달아 나오지 않게 해요. */
window.WPTalkRandom = function (root) {
  var all = [];
  window.WP_TALK.forEach(function (t) { t.qs.forEach(function (q) { all.push({ t: t, q: q }); }); });
  var last = -1;
  var q = root.querySelector(".tk-q"), tag = root.querySelector(".tk-topic"), link = root.querySelector(".tk-link"), btn = root.querySelector(".tk-shuffle");
  function show() {
    var i; do { i = Math.floor(Math.random() * all.length); } while (all.length > 1 && i === last);
    last = i;
    var x = all[i];
    tag.textContent = x.t.icon + " " + x.t.no + ". " + x.t.title;
    q.textContent = x.q;
    link.href = tag.href = "/talk/" + x.t.no + "/";
    root.classList.remove("tk-pop"); void root.offsetWidth; root.classList.add("tk-pop");
  }
  btn.addEventListener("click", show);
  show();
};
